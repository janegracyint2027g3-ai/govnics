// api/compliance/generate.js
// POST /api/compliance/generate — Generate compliance checklist for authenticated user's company

import { getAuthenticatedUser } from "../lib/auth.js";
import { redis, KEYS } from "../lib/redis.js";
import { matchRules } from "../lib/regulatoryRules.js";
import { setCorsHeaders, handleOptions, successResponse, errorResponse } from "../lib/cors.js";
import { auditLog } from "../lib/auth.js";

export default async function handler(req, res) {
  setCorsHeaders(res, req.headers.origin);
  if (handleOptions(req, res)) return;

  if (req.method !== "POST") {
    return errorResponse(res, 405, "Method Not Allowed");
  }

  try {
    const user = await getAuthenticatedUser(req);
    if (!user) return errorResponse(res, 401, "Not authenticated.");

    if (!user.companyId) {
      return errorResponse(res, 404, "No company profile found. Please complete company registration.");
    }

    // Fetch company profile
    const companyRaw = await redis.get(KEYS.company(user.companyId));
    if (!companyRaw) {
      return errorResponse(res, 404, "Company profile not found.");
    }
    const company = typeof companyRaw === "string" ? JSON.parse(companyRaw) : companyRaw;

    // Validate company ownership
    if (company.ownerId !== user.userId) {
      return errorResponse(res, 403, "Not authorised to generate checklist for this company.");
    }

    // ─── Run Matching Engine ──────────────────────────────────────────────
    const matchedRules = matchRules({
      country: company.country,
      state: company.state,
      industry: company.industrySector,
      subIndustry: company.subIndustry,
      companySize: company.companySize,
      businessOperations: company.businessOperations || [],
    });

    // ─── Check for existing checklist ─────────────────────────────────────
    const existingRaw = await redis.get(KEYS.checklist(user.companyId));
    let existingChecklist = null;
    if (existingRaw) {
      existingChecklist = typeof existingRaw === "string" ? JSON.parse(existingRaw) : existingRaw;
    }

    // Merge existing statuses into newly generated items
    const checklistItems = matchedRules.map((rule) => {
      const existing = existingChecklist?.items?.find((i) => i.ruleId === rule.ruleId);
      return {
        ...rule,
        completionStatus: existing?.completionStatus || "Not Started",
        notes: existing?.notes || "",
        internalDeadline: existing?.internalDeadline || null,
        uploadedDocuments: existing?.uploadedDocuments || [],
      };
    });

    // ─── Build Checklist Object ───────────────────────────────────────────
    const checklist = {
      companyId: user.companyId,
      generatedAt: new Date().toISOString(),
      generatedBy: user.userId,
      profileSnapshot: {
        country: company.country,
        state: company.state,
        industrySector: company.industrySector,
        subIndustry: company.subIndustry,
        companySize: company.companySize,
        businessOperations: company.businessOperations,
      },
      items: checklistItems,
      totalItems: checklistItems.length,
      disclaimer:
        "This checklist is generated by a rules-based matching engine for informational purposes only. It is not a legal opinion or guarantee of compliance. Always consult qualified legal and compliance professionals for advice specific to your jurisdiction and circumstances.",
    };

    // ─── Persist Checklist ────────────────────────────────────────────────
    await redis.set(KEYS.checklist(user.companyId), JSON.stringify(checklist));
    await auditLog(user.userId, "CHECKLIST_GENERATED", {
      companyId: user.companyId,
      totalItems: checklistItems.length,
    });

    return successResponse(res, { checklist });
  } catch (err) {
    console.error("[compliance/generate] Error:", err);
    return errorResponse(res, 500, "Error generating compliance checklist.");
  }
}
