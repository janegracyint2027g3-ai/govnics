export function getAgentProfile(agentId) {
  const found = AGENT_PROFILES.find((p) => p.agentId === agentId) ||
                EXTRACTION_AGENTS.find((p) => p.agentId === agentId);
  return found || AGENT_PROFILES[0];
}

export function getAllAgentProfiles(options = {}) {
  if (options.includeExtraction) {
    return [...AGENT_PROFILES, ...EXTRACTION_AGENTS];
  }
  return AGENT_PROFILES;
}

