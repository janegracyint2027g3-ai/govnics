export function getOfferingEbooks(offeringFilter = "All") {
  if (!offeringFilter || offeringFilter === "All") return ELIBRARY_OFFERING_EBOOKS;
  return ELIBRARY_OFFERING_EBOOKS.filter(e => e.offering === offeringFilter);
}

export function getEbookById(contentId) {
  return ELIBRARY_OFFERING_EBOOKS.find(e => e.contentId === contentId) || null;
}

