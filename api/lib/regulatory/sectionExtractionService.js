export function getAllProvisions() {
  return STRUCTURED_PROVISIONS;
}

export function getProvisionsByJurisdiction(jurisdictionLevel, stateName = null) {
  if (stateName) {
    return STRUCTURED_PROVISIONS.filter(p => p.stateOrUtName?.toLowerCase().includes(stateName.toLowerCase()));
  }
  return STRUCTURED_PROVISIONS.filter(p => p.jurisdictionLevel === jurisdictionLevel);
}

export function getProvisionsByOffering(offering) {
  return STRUCTURED_PROVISIONS.filter(p => p.offering === offering);
}

export function getProvisionById(provisionId) {
  return STRUCTURED_PROVISIONS.find(p => p.provisionId === provisionId) || null;
}

