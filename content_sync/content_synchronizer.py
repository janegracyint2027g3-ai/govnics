"""
content_synchronizer.py – Idempotent sync engine.

Orchestrates:
1. Extract content from source
2. Compare with previous snapshot
3. If changes exist, update/create pages in WordPress
4. Never delete production pages: mark removed pages as missing
5. Save snapshot, generate sync report in JSON and Markdown
"""
import argparse
import json
import logging
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any

from config import (
    HIERARCHY_JSON,
    CMS_MAPPING_JSON,
    SYNC_REPORT_JSON,
    SYNC_REPORT_MD,
    LOGS_DIR,
)
from hierarchy_extractor import run_extraction
from change_detector import ChangeDetector
from cms_structure_creator import CMSStructureCreator

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s – %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(LOGS_DIR / "content_synchronizer.log", encoding="utf-8"),
    ],
)
log = logging.getLogger("synchronizer")


def generate_markdown_report(report: Dict[str, Any]) -> str:
    now_str = report.get("timestamp", datetime.now(timezone.utc).isoformat())
    counts = report.get("diff", {}).get("counts", {})
    cms_summary = report.get("cms_summary", {})

    lines = [
        "# GOVENICS Digital Presence -> WordPress Sync Report",
        f"**Timestamp:** `{now_str}`  ",
        f"**Mode:** `{'DRY RUN' if report.get('dry_run') else 'LIVE EXECUTION'}`  ",
        "",
        "## Summary of Changes Detected",
        f"- **Total Current Pages:** {counts.get('total_current', 0)}",
        f"- **New Pages:** {counts.get('new', 0)}",
        f"- **Updated Pages:** {counts.get('updated', 0)}",
        f"- **Moved Pages:** {counts.get('moved', 0)}",
        f"- **Removed Pages:** {counts.get('removed', 0)} *(Safely archived / not deleted)*",
        f"- **Unchanged Pages:** {counts.get('unchanged', 0)}",
        "",
        "## CMS Sync Execution Summary",
        f"- **Pages Created in WP:** {cms_summary.get('created', 0)}",
        f"- **Pages Updated in WP:** {cms_summary.get('updated', 0)}",
        f"- **Total Synchronized:** {cms_summary.get('total', 0)}",
        "",
    ]

    new_pages = report.get("diff", {}).get("new_pages", [])
    if new_pages:
        lines.append("### New Pages Added")
        for p in new_pages:
            lines.append(f"- [{p.get('title')}]({p.get('url')}) (`{p.get('path')}`)")
        lines.append("")

    updated_pages = report.get("diff", {}).get("updated_pages", [])
    if updated_pages:
        lines.append("### Pages Modified")
        for p in updated_pages:
            pg = p.get("page", {})
            lines.append(f"- [{pg.get('title')}]({pg.get('url')}) (`{pg.get('path')}`)")
        lines.append("")

    removed_pages = report.get("diff", {}).get("removed_pages", [])
    if removed_pages:
        lines.append("### Removed Pages (Retained safely in CMS)")
        for p in removed_pages:
            lines.append(f"- {p.get('title')} (`{p.get('path')}`)")
        lines.append("")

    lines.append("---")
    lines.append("*Report automatically generated by GOVENICS CMS Sync Pipeline.*")
    return "\n".join(lines)


def run_sync(dry_run: bool = True, use_playwright: bool = True) -> Dict[str, Any]:
    log.info("Starting sync run (dry_run=%s)", dry_run)
    start_time = time.time()

    # Step 1: Extraction
    log.info("Step 1: Extracting site hierarchy...")
    hierarchy_data = run_extraction(use_playwright=use_playwright)

    # Step 2: Change detection
    log.info("Step 2: Detecting changes against previous snapshot...")
    detector = ChangeDetector()
    diff = detector.compute_diff(hierarchy_data)

    # Step 3: CMS Replication
    log.info("Step 3: Synchronizing structure to WordPress CMS...")
    creator = CMSStructureCreator(dry_run=dry_run)
    mapping = creator.execute(hierarchy_data)

    # Step 4: Update snapshot if live
    if not dry_run:
        detector.save_as_snapshot(hierarchy_data)

    duration = round(time.time() - start_time, 2)
    report = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "dry_run": dry_run,
        "duration_seconds": duration,
        "diff": diff,
        "cms_summary": mapping.get("summary", {}),
    }

    # Save JSON & MD reports
    SYNC_REPORT_JSON.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    md_content = generate_markdown_report(report)
    SYNC_REPORT_MD.write_text(md_content, encoding="utf-8")

    log.info("Sync completed in %s seconds. Reports saved to %s and %s", duration, SYNC_REPORT_JSON, SYNC_REPORT_MD)
    print(f"✅ Sync finished in {duration}s! Report generated at {SYNC_REPORT_MD}")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="GOVENICS Content Synchronizer")
    parser.add_argument("--execute", action="store_true", help="Execute changes in WordPress CMS")
    parser.add_argument("--no-playwright", action="store_true", help="Skip Playwright, use HTTP fallback")
    args = parser.parse_args()

    run_sync(dry_run=not args.execute, use_playwright=not args.no_playwright)

